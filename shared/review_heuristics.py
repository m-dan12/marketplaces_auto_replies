"""Общая эвристика для ответов на 5★ отзывы: детект скрытого негатива и стандартные тексты.

Вынесено из recommendations.py, чтобы Ozon и Wildberries использовали одни и те же
правила определения "фальшиво-позитивных" 5★ отзывов и одинаковые группы товаров
для текста рекомендаций (постельное бельё: наволочки/простыни/пододеяльники).
"""

import re
from typing import Dict, List, Optional

# Стоп-слова для определения негативных 5★ отзывов (покупатель поставил 5★,
# но в тексте жалуется на брак, размер и т.п.)
STOP_WORDS = [
    'брак', 'бракован', 'дефект', 'дыр', 'дыра', 'порван', 'рван',
    'шов разош', 'затяжк', 'зацеп', 'нитк торчат', 'крив', 'кос',
    'перекош', 'пятн', 'гряз', 'желт', 'плесен', 'мокр', 'сыр',
    'влажн', 'тонк', 'просвеч', 'жестк', 'колюч', 'царап', 'скрипит',
    'катыш', 'скатал', 'скаталось', 'лин', 'полинял', 'выцвел',
    'выцвело', 'не соответствует', 'не совпад', 'обман', 'поддел',
    'фейк', 'мал', 'коротк', 'узк', 'не хватает', 'недокомплект',
    'не полный', 'не пришло', 'не достав', 'упаковка порван',
    'упаковка вскрыт', 'упаковка ужас', 'возврат', 'ужас', 'кошмар',
    'отврат', 'дерьм', 'хлам', 'плох', 'разочар', 'не совет',
    'не рекоменд',
]

NEG_PATTERNS = [
    r'\bне\s+рекоменд',
    r'\bне\s+совет',
    r'\bплох(о|ая|ие|ой|ий)\b',
    r'\bужас(но|ный|ная|ные)?\b',
    r'\bразочар',
    r'\bне\s+качеств',
    r'\bкачество\s+(плох|ужас|ниже)',
]

NEG_RE = re.compile('|'.join(f'(?:{p})' for p in NEG_PATTERNS), flags=re.IGNORECASE)

# Шаблоны вступлений для ответов на 5★ отзывы с рекомендациями.
# {brand} подставляется вызывающей стороной, например «Сказка» или «МилкиГарден».
INTRO_TEMPLATES = [
    'Спасибо за ваш отзыв! Рады, что вы выбрали {brand} 🙂',
    'Благодарим за 5⭐ и выбор {brand} ✨',
    'Спасибо за высокую оценку! Пусть будет уютно вместе с {brand} 😊',
    'Спасибо за отзыв! Очень приятно, что выбрали {brand} 🌠',
]

# Стандартные ответы без рекомендаций (нет остатков / негатив в 5★ / товар не найден)
STANDARD_5STAR_REPLY_VARIANTS = [
    'Благодарим за высокую оценку! 💙 Спасибо, что нашли время поделиться впечатлением. '
    'Хорошего вам настроения и приятных покупок! 😊',
    'Спасибо за 5 звёзд! ⭐ Нам очень приятно получать такую обратную связь. '
    'Надеемся, товар будет радовать вас и дальше 🌸',
    'Спасибо за ваш отзыв! 😊 Очень приятно, что вы выбрали наш товар. '
    'Будем рады видеть вас снова! ✨',
]

MAX_REPLY_LEN = 5000

# Порядок и подписи групп постельного белья в тексте рекомендаций
GROUPS_ORDER = ['Простыня натяжная', 'Простыня классическая', 'Пододеяльник', 'Наволочки']

GROUP_TITLES: Dict[str, str] = {
    'Простыня натяжная': 'Простынь на резинке',
    'Простыня классическая': 'Простынь классическая',
    'Пододеяльник': 'Пододеяльник',
    'Наволочки': 'Наволочки',
}


def looks_negative_5star(text: Optional[str]) -> bool:
    """
    Проверяет, является ли 5★ отзыв скрыто негативным (жалобы в тексте).

    Args:
        text: Текст отзыва (может включать плюсы/минусы, склеенные через " | ")

    Returns:
        True, если найдены негативные маркеры.
    """
    if not text:
        return False

    t = text.strip().lower()
    t_clean = re.sub(r'[^\w\s]', ' ', t)
    t_clean = re.sub(r'\s+', ' ', t_clean).strip()

    if NEG_RE.search(t):
        return True

    return any(sw in t_clean for sw in STOP_WORDS)


def build_intro(brand_name: str) -> str:
    """
    Выбирает случайное вступление для ответа с рекомендациями.

    Args:
        brand_name: Название бренда, например «Сказка»

    Returns:
        Готовая фраза-вступление
    """
    import random

    return random.choice(INTRO_TEMPLATES).format(brand=brand_name)


def pick_standard_reply() -> str:
    """Возвращает случайный стандартный ответ на 5★ отзыв (без рекомендаций)."""
    import random

    return random.choice(STANDARD_5STAR_REPLY_VARIANTS)


def build_grouped_text(items_by_group: Dict[str, List[str]], max_per_group: int = 5) -> str:
    """
    Собирает многострочный текст рекомендаций из уже сгруппированных подписей товаров.

    Args:
        items_by_group: {группа: [готовые подписи товаров, ...]}
        max_per_group: Сколько товаров показывать на группу

    Returns:
        Текст вида "Простынь на резинке: ..., ...\\nНаволочки: ..."
    """
    lines: List[str] = []
    for group in GROUPS_ORDER:
        items = items_by_group.get(group, [])
        if not items:
            continue
        title = GROUP_TITLES.get(group, group)
        lines.append(f"{title}: {', '.join(items[:max_per_group])}")
    return '\n'.join(lines)
