"""Общая эвристика для ответов на отзывы: детект скрытого негатива в 5★, детект
конкретной проблемы в 1-4★ (для Gemini, см. shared/gemini_client.py) и стандартные тексты.

Вынесено из recommendations.py, чтобы Ozon и Wildberries использовали одни и те же
правила определения "фальшиво-позитивных" 5★ отзывов и одинаковые группы товаров
для текста рекомендаций (постельное бельё: наволочки/простыни/пододеяльники).
"""

import re
from typing import Dict, List, Optional

NEG_PATTERNS = [
    r'\bне\s+рекоменд',
    r'\bне\s+совет',
    r'\bплох(о|ая|ие|ой|ий)\b',
    r'\bужас(но|ный|ная|ные)?\b',
    r'\bразочар',
    r'\bне\s+качеств',
    r'\bкачество\s+(плох|ужас|ниже)',
]

NEG_RE = re.compile('|'.join(f'(?:{p})' for p in NEG_PATTERNS), flags=re.IGNORECASE)

# Шаблоны вступлений для ответов на 5★ отзывы с рекомендациями.
# {brand} подставляется вызывающей стороной, например «Сказка» или «МилкиГарден».
INTRO_TEMPLATES = [
    'Спасибо за ваш отзыв! Рады, что вы выбрали {brand} 🙂',
    'Благодарим за 5⭐ и выбор {brand} ✨',
    'Спасибо за высокую оценку! Пусть будет уютно вместе с {brand} 😊',
    'Спасибо за отзыв! Очень приятно, что выбрали {brand} 🌠',
]

# Стандартные ответы без рекомендаций (нет остатков / негатив в 5★ / товар не найден)
STANDARD_5STAR_REPLY_VARIANTS = [
    'Благодарим за высокую оценку! 💙 Спасибо, что нашли время поделиться впечатлением. '
    'Хорошего вам настроения и приятных покупок! 😊',
    'Спасибо за 5 звёзд! ⭐ Нам очень приятно получать такую обратную связь. '
    'Надеемся, товар будет радовать вас и дальше 🌸',
    'Спасибо за ваш отзыв! 😊 Очень приятно, что вы выбрали наш товар. '
    'Будем рады видеть вас снова! ✨',
]

# Единый список категорий негатива в отзыве — общий и для детекта скрытого
# негатива в 5★ (looks_negative_5star), и для подбора конкретной проблемы
# в 1-4★ для Gemini (см. shared/gemini_client.py). Раньше это были два разных
# списка слов (STOP_WORDS + _ISSUE_PATTERNS), которые дублировали друг друга
# и расходились между собой — теперь один источник правды.
#
# У категорий из ISSUE_LABELS (ниже) есть текстовая метка — это "явная
# нестыковка", отзыв уходит в Gemini за адресным ответом. "general_negative" —
# без метки, это просто общий признак недовольства без конкретики: для 5★
# этого достаточно, чтобы не показывать рекомендации, а для 1-4★ Gemini не
# вызывается — остаётся обычный фиксированный шаблон (см. detect_review_issue).
_ISSUE_PATTERNS: Dict[str, List[str]] = {
    "size_mismatch": [
        'размер не соответств', 'не подошел размер', 'не подошёл размер',
        'маломерит', 'большемерит', 'мал для', 'велик для', 'не по размеру',
        'мал', 'коротк', 'узк',
    ],
    "fabric_quality": [
        'текстура', 'ткань не', 'материал не', 'жестк', 'колюч', 'тонк',
        'просвеч', 'не приятн', 'некачественная ткань', 'царап', 'скрипит',
        'катыш', 'скатал', 'скаталось',
    ],
    "defect": [
        'брак', 'бракован', 'дефект', 'дыр', 'дыра', 'порван', 'рван',
        'шов разош', 'затяжк', 'зацеп', 'нитк торчат', 'крив', 'кос',
        'перекош', 'пятн', 'гряз', 'желт', 'плесен', 'мокр', 'сыр',
        'влажн', 'лин', 'полинял', 'выцвел', 'выцвело',
    ],
    "color_mismatch": [
        'цвет не соответств', 'цвет отличается', 'другой цвет', 'не тот цвет',
        'на фото другой',
    ],
    "wrong_item": [
        'не тот товар', 'перепутали', 'не то что заказыв', 'другая модель',
        'не хватает', 'недокомплект', 'не полный', 'не совпад', 'обман',
        'поддел', 'фейк',
    ],
    "general_negative": [
        'не соответствует', 'не пришло', 'не достав', 'упаковка порван',
        'упаковка вскрыт', 'упаковка ужас', 'возврат', 'ужас', 'кошмар',
        'отврат', 'дерьм', 'хлам', 'плох', 'разочар', 'не совет',
        'не рекоменд',
    ],
}

# Метки категорий для промпта Gemini — только для "явных нестыковок"
# (см. комментарий у _ISSUE_PATTERNS). "general_negative" сюда не входит.
ISSUE_LABELS: Dict[str, str] = {
    "size_mismatch": "не подошёл размер (мало/велико/не соответствует заявленному)",
    "fabric_quality": "не понравился материал или текстура ткани",
    "defect": "брак или дефект товара",
    "color_mismatch": "цвет отличается от описания/фото",
    "wrong_item": "привезли не тот товар/комплектацию, что заказывали",
}


def detect_review_issue(text: Optional[str]) -> Optional[str]:
    """
    Определяет категорию проблемы в отзыве по тексту.

    Args:
        text: Текст отзыва (может включать плюсы/минусы, склеенные через " | ")

    Returns:
        Ключ категории из `_ISSUE_PATTERNS` (например, "size_mismatch" или
        "general_negative"), или None, если явных маркеров недовольства нет.
        Для решения "звать ли Gemini" (только 1-4★) вызывающая сторона должна
        дополнительно проверить `category in ISSUE_LABELS` — "general_negative"
        не считается "явной нестыковкой".
    """
    if not text:
        return None

    t = text.strip().lower()

    for category, patterns in _ISSUE_PATTERNS.items():
        if any(p in t for p in patterns):
            return category

    return None


MAX_REPLY_LEN = 5000

# Порядок и подписи групп постельного белья в тексте рекомендаций
GROUPS_ORDER = ['Простыня натяжная', 'Простыня классическая', 'Пододеяльник', 'Наволочки']

GROUP_TITLES: Dict[str, str] = {
    'Простыня натяжная': 'Простынь на резинке',
    'Простыня классическая': 'Простынь классическая',
    'Пододеяльник': 'Пододеяльник',
    'Наволочки': 'Наволочки',
}


def looks_negative_5star(text: Optional[str]) -> bool:
    """
    Проверяет, является ли 5★ отзыв скрыто негативным (жалобы в тексте).

    Использует ту же категоризацию, что и `detect_review_issue` (см. выше) —
    в отличие от 1-4★, для 5★ не важно, какая именно категория нашлась
    (включая "general_negative"): любая — повод не показывать рекомендации.

    Args:
        text: Текст отзыва (может включать плюсы/минусы, склеенные через " | ")

    Returns:
        True, если найдены негативные маркеры.
    """
    if not text:
        return False

    if NEG_RE.search(text.strip().lower()):
        return True

    return detect_review_issue(text) is not None


def build_intro(brand_name: str) -> str:
    """
    Выбирает случайное вступление для ответа с рекомендациями.

    Args:
        brand_name: Название бренда, например «Сказка»

    Returns:
        Готовая фраза-вступление
    """
    import random

    return random.choice(INTRO_TEMPLATES).format(brand=brand_name)


def pick_standard_reply() -> str:
    """Возвращает случайный стандартный ответ на 5★ отзыв (без рекомендаций)."""
    import random

    return random.choice(STANDARD_5STAR_REPLY_VARIANTS)


def build_grouped_text(items_by_group: Dict[str, List[str]], max_per_group: int = 5) -> str:
    """
    Собирает многострочный текст рекомендаций из уже сгруппированных подписей товаров.

    Args:
        items_by_group: {группа: [готовые подписи товаров, ...]}
        max_per_group: Сколько товаров показывать на группу

    Returns:
        Текст вида "Простынь на резинке: ..., ...\\nНаволочки: ..."
    """
    lines: List[str] = []
    for group in GROUPS_ORDER:
        items = items_by_group.get(group, [])
        if not items:
            continue
        title = GROUP_TITLES.get(group, group)
        lines.append(f"{title}: {', '.join(items[:max_per_group])}")
    return '\n'.join(lines)
